#[inline(never)]
fn process(_inp:&str) -> (i64, i64, i64)
{
    let mut a = 585;
    let part1 = evaluate(a, false);
    let mut b = a*2;
    let mut p2;
    let mut iterations = 0;
    let mut p1 = part1;
    loop {
        iterations += 1;
        p2 = evaluate(b, true);
        if p2 == 0 {break;}

        let slope = (a-b) as f64 / (p2-p1) as f64;
        let next_guess = a + (p1 as f64 * slope).round() as i64;
        a = b;
        b = next_guess;
        p1 = p2;
        if iterations > 10 {break;}
    }
    (part1, b, iterations)
}

